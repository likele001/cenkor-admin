def main() -> None:
    url = get_settings().DATABASE_URL_SYNC
    engine = create_engine(url)
    upsert = text(
        """
        INSERT INTO app_intros (product, app_key, summary, highlights, tags, screenshots, long_description)
        VALUES (:product, :app_key, :summary, :highlights, :tags, :screenshots, :long_description)
        ON CONFLICT ON CONSTRAINT uq_app_intro_product_key DO UPDATE SET
            summary = EXCLUDED.summary,
            highlights = EXCLUDED.highlights,
            tags = EXCLUDED.tags,
            screenshots = EXCLUDED.screenshots,
            long_description = EXCLUDED.long_description,
            updated_at = now()
        """
    )
    n = 0
    with engine.begin() as conn:
        for app_key, d in INTROS.items():
            conn.execute(upsert, {
                "product": PRODUCT,
                "app_key": app_key,
                "summary": d["summary"],
                "highlights": json.dumps(d["highlights"], ensure_ascii=False),
                "tags": json.dumps(d["tags"], ensure_ascii=False),
                "screenshots": json.dumps([]),
                "long_description": d["long_description"],
            })
            n += 1
    print(f"SEEDED {n} app_intros (product={PRODUCT})")


if __name__ == "__main__":
    main()
